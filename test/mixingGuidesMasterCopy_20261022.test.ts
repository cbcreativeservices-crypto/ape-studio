/**
 * Owner 2026-10-22: the 50 shipped mixing-guide files are the MASTER COPY. Every
 * fix since the 2026-10-07 conversion (~1,870 lines) was made in them, so
 * scripts/mixing-guides/convert.py must never overwrite a guide that differs.
 * (Checked by hand 2026-10-22: against the real repo it refused all 52 files and
 * wrote nothing; into an empty scratch root it still wrote all 50.)
 */
import assert from 'node:assert/strict';
import { readdirSync, readFileSync } from 'node:fs';
import { join } from 'node:path';
import { describe, it } from 'node:test';

const ROOT = join(import.meta.dirname, '..');
const read = (p: string) => readFileSync(join(ROOT, p), 'utf8').replace(/\r\n/g, '\n');
const DATA = 'src/screens/lab/mixingGuides/data';
const convert = read('scripts/mixing-guides/convert.py');

describe('mixing guides: shipped files are the master copy', () => {
  it('convert.py writes only through PENDING, after the lock', () => {
    const lock = convert.indexOf('if changed and "--overwrite-hand-edits" not in sys.argv:');
    assert.ok(lock > 0, 'the lock is present');
    // Every write to disk of a guide/index/load file happens after the lock.
    const opens = [...convert.matchAll(/open\([^)]*"w"/g)].map((m) => m.index ?? 0);
    const writesBeforeLock = opens.filter((i) => i < lock && !/report_path/.test(convert.slice(i - 80, i)));
    assert.deepEqual(writesBeforeLock, [], 'no file is opened for writing before the lock');
    assert.match(convert, /PENDING\[os\.path\.join\(GUIDES, fname\)\] = \(/);
    assert.match(convert, /PENDING\[os\.path\.join\(OUT, "index\.ts"\)\] = \(/);
    assert.match(convert, /PENDING\[os\.path\.join\(OUT, "load\.ts"\)\] = \(/);
  });

  it('the lock compares content (line endings ignored) and refuses with exit 2', () => {
    assert.match(convert, /if _norm\(fh\.read\(\)\) != _norm\(text\):\n\s+changed\.append\(path\)/);
    assert.match(convert, /sys\.exit\(2\)/);
    assert.match(convert, /MASTER-COPY LOCK \(owner 2026-10-22\)/);
  });

  it('every shipped guide, index.ts and load.ts says it is the master copy', () => {
    const guides = readdirSync(join(ROOT, DATA, 'guides')).filter((f) => f.endsWith('.ts'));
    assert.equal(guides.length, 50);
    for (const f of guides) {
      const head = read(`${DATA}/guides/${f}`).slice(0, 600);
      assert.match(head, /MASTER COPY: first generated by/, f);
      assert.match(head, /every fix since is made HERE\. convert\.py will not overwrite it\./, f);
      assert.doesNotMatch(head, /Edit the\n \* conversion \(scripts\/mixing-guides\/edits\.py\), not this file/, f);
    }
    assert.match(read(`${DATA}/index.ts`), /MASTER COPY — first generated by scripts\/mixing-guides\/convert\.py/);
    assert.match(read(`${DATA}/load.ts`), /MASTER COPY —\n \* first generated by scripts\/mixing-guides\/convert\.py, which will not overwrite it\./);
  });

  it('edits.py and the lab doc say where fixes go now', () => {
    assert.match(read('scripts/mixing-guides/edits.py'), /^"""HISTORICAL \(owner 2026-10-22\)/);
    assert.match(read('docs/labs/mixing/MIXING_GUIDES_LAB.md'), /\*\*MASTER COPY \(owner 2026-10-22\)\.\*\*/);
  });
});
