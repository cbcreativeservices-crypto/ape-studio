/**
 * Generates src/screens/lab/miking/data/lessonArtLoader.ts from data/lessonArt.ts.
 *
 * Why (2026-10-23, measured on a Pixel 7 Pro): the first Miking lesson open
 * evaluated data/lessonArt.ts — every lesson's drawings, 2.75 s. The loader
 * gives each lesson id a thunk that `require`s only the modules its own entry
 * names, so opening a lesson evaluates only that lesson's art.
 *
 * Reads the index's three shapes: the literal initialiser (`const ART … = {…}`),
 * one-line `ART.ID = <expr>;` entries, and `Object.assign(ART, GROUP)` group
 * registries (their ids parsed from the group file). Local consts the entries
 * use (e.g. F05_FOLEY) are inlined into the thunk. Re-run after adding a lesson:
 *   node scripts/gen-miking-art-loader.mjs
 * test/mikingArtLoader_20261024.test.ts checks coverage and the shapes.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const DATA = path.join(ROOT, 'src/screens/lab/miking/data');
const src = readFileSync(path.join(DATA, 'lessonArt.ts'), 'utf8').replace(/\r\n/g, '\n');

/** imported name -> module path (value imports only). */
const imported = new Map();
for (const m of src.matchAll(/^import \{([^}]*)\} from '([^']+)';$/gm)) {
  for (const part of m[1].split(',')) {
    const name = part.trim().split(/\s+as\s+/).pop().trim();
    if (name && !name.startsWith('type ')) imported.set(name, m[2]);
  }
}
/** local `const NAME = <expr>;` (one line) */
const locals = new Map();
for (const m of src.matchAll(/^const (\w+) = (.+);$/gm)) if (m[1] !== 'ART') locals.set(m[1], m[2]);

// Identifiers an expression USES — object keys (`key: value`) and string
// contents are not uses (a key like `StrikeSequence:` would otherwise pull in a
// same-named import from another lesson).
const idents = (expr) =>
  new Set(expr.replace(/'[^']*'/g, "''").replace(/\b\w+\s*:(?!:)/g, ' ').match(/\b[A-Za-z_]\w*\b/g) ?? []);

/** Build a thunk body for an expression: requires for the imports it names. */
function thunk(expr) {
  const pre = [];
  const used = new Set();
  const visit = (e) => {
    for (const id of idents(e)) {
      if (locals.has(id) && !used.has(id)) {
        used.add(id);
        visit(locals.get(id));
        pre.push(`const ${id} = ${locals.get(id)};`);
      } else if (imported.has(id)) used.add(id);
    }
  };
  visit(expr);
  const byMod = new Map();
  for (const id of used) if (imported.has(id)) {
    const mod = imported.get(id);
    if (!byMod.has(mod)) byMod.set(mod, []);
    byMod.get(mod).push(id);
  }
  const reqs = [...byMod].map(([mod, names]) => `const { ${names.sort().join(', ')} } = require('${mod}');`);
  return `() => { ${[...reqs, ...pre].join(' ')} return ${expr}; }`;
}

const entries = [];
// 1. the literal initialiser: top-level `  KEY: <expr>,` entries, an entry may span lines
const init = /const ART: Record<string, LessonArt> = \{\n([\s\S]*?)\n\};/.exec(src);
if (!init) throw new Error('ART initialiser not found');
let cur = null;
for (const line of init[1].split('\n')) {
  const m = /^ {2}(\w+): (.*)$/.exec(line);
  if (m) {
    if (cur) entries.push(cur);
    cur = { id: m[1], expr: m[2] };
  } else if (cur && !/^\s*\/\//.test(line)) cur.expr += ' ' + line.trim();
}
if (cur) entries.push(cur);
for (const e of entries) e.expr = e.expr.replace(/,\s*$/, '').trim();
// 2. one-line assignments
for (const m of src.matchAll(/^ART\.(\w+) = (.+);$/gm)) entries.push({ id: m[1], expr: m[2] });
// 3. group registries
for (const m of src.matchAll(/^Object\.assign\(ART, (\w+)\);$/gm)) {
  const mod = imported.get(m[1]);
  const file = ['.tsx', '.ts'].map((x) => path.join(DATA, mod + x)).find((f) => { try { readFileSync(f); return true; } catch { return false; } });
  const gsrc = readFileSync(file, 'utf8').replace(/\r\n/g, '\n');
  const block = new RegExp(`export const ${m[1]}[^=]*= \\{\\n([\\s\\S]*?)\\n\\};`).exec(gsrc);
  if (!block) throw new Error(`group ${m[1]}: object not found in ${file}`);
  for (const k of block[1].matchAll(/^ {2}(\w+): /gm)) entries.push({ id: k[1], expr: `${m[1]}[${JSON.stringify(k[1])}]` });
}
const seen = new Set();
for (const e of entries) {
  if (seen.has(e.id)) throw new Error(`duplicate id ${e.id}`);
  seen.add(e.id);
}

const body = entries.map((e) => `  ${JSON.stringify(e.id)}: ${thunk(e.expr)},`).join('\n');
const out = `/**
 * GENERATED by scripts/gen-miking-art-loader.mjs from data/lessonArt.ts — do not
 * edit by hand; re-run the script after adding a lesson.
 *
 * The lesson screen resolves art HERE, one lesson at a time (2026-10-23: the
 * whole art index cost 2.75 s on the first open, Pixel 7 Pro). Each thunk
 * requires only the modules its own entry names. data/lessonArt.ts stays the
 * source of truth; test/mikingArtLoader_20261024.test.ts pins coverage.
 */
/* eslint-disable @typescript-eslint/no-var-requires, @typescript-eslint/no-explicit-any */
import type { LessonArt } from '../engine/scene/sceneTypes.ts';

declare const require: (path: string) => any;

const LOADERS: Record<string, () => LessonArt> = {
${body}
};

const loaded: Record<string, LessonArt | undefined> = {};

/** The art for this lesson, loading only its own modules. */
export function lessonArt(id: string): LessonArt | undefined {
  if (id in loaded) return loaded[id];
  const load = LOADERS[id];
  const art = load ? load() : undefined;
  loaded[id] = art;
  return art;
}

export const ART_LOADER_IDS: readonly string[] = Object.keys(LOADERS);
`;
writeFileSync(path.join(DATA, 'lessonArtLoader.ts'), out);
console.log(`lessonArtLoader.ts: ${entries.length} lessons`);
