/**
 * Generates src/screens/lab/miking/data/lessonLoader.ts from data/lessons.ts.
 *
 * Why (2026-10-23, measured on the Pixel): opening the FIRST Miking lesson
 * froze the app ~15 s — 10.9 s of it evaluating data/lessons.ts, which
 * statically imports all 129 lessons. The loader gives each lesson id its own
 * `require` thunk (Metro evaluates a module on its first require), so opening
 * a lesson evaluates only that lesson's module (or its shared group module).
 *
 * data/lessons.ts stays the eager table for Node tests and the plan-case
 * audits; test/mikingLessonLoader_20261023.test.ts proves every loader entry
 * returns the SAME object as lessonById. Re-run after adding a lesson:
 *   node scripts/gen-miking-lesson-loader.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const DATA = path.join(ROOT, 'src/screens/lab/miking/data');
const src = readFileSync(path.join(DATA, 'lessons.ts'), 'utf8').replace(/\r\n/g, '\n');

// symbol -> relative module path
const from = new Map();
for (const m of src.matchAll(/import \{ (\w+) \} from '([^']+)';/g)) from.set(m[1], m[2]);

/** [id, modulePath, accessor] in table order. */
const entries = [];
// The table's literal initialiser: `const LESSON_CONTENT … = { M01: M01_LESSON, … };`
const init = /const LESSON_CONTENT[^=]*= \{([^}]*)\};/.exec(src);
if (init) for (const m of init[1].matchAll(/(\w+): (\w+),?/g)) entries.push([m[1], from.get(m[2]), `.${m[2]}`]);
for (const line of src.split('\n')) {
  let m = /^LESSON_CONTENT\.(\w+) = (\w+);/.exec(line);
  if (m) {
    entries.push([m[1], from.get(m[2]), `.${m[2]}`]);
    continue;
  }
  m = /^Object\.assign\(LESSON_CONTENT, (\w+)\);/.exec(line);
  if (m) {
    const mod = from.get(m[1]);
    const ns = await import(pathToFileURL(path.join(DATA, mod)).href);
    for (const id of Object.keys(ns[m[1]])) entries.push([id, mod, `.${m[1]}[${JSON.stringify(id)}]`]);
  }
}
for (const [id, mod] of entries) if (!mod) throw new Error(`no import found for ${id}`);
const ids = new Set();
for (const [id] of entries) {
  if (ids.has(id)) throw new Error(`duplicate id ${id}`);
  ids.add(id);
}

const body = entries.map(([id, mod, acc]) => `  ${JSON.stringify(id)}: () => require('${mod}')${acc},`).join('\n');
const out = `/**
 * GENERATED by scripts/gen-miking-lesson-loader.mjs from data/lessons.ts — do
 * not edit by hand; re-run the script after adding a lesson.
 *
 * The app resolves a lesson HERE, one module at a time (2026-10-23: importing
 * data/lessons.ts evaluated all ${entries.length} lessons on the first open — 10.9 s
 * of a ~15 s freeze on a Pixel 7 Pro). Metro evaluates each module on its
 * first require, so only the opened lesson is loaded. Node tests keep using
 * data/lessons.ts; test/mikingLessonLoader_20261023.test.ts pins the two equal.
 */
import type { Lesson } from '../engine/model/types.ts';

declare const require: (path: string) => any; // eslint-disable-line @typescript-eslint/no-explicit-any

const LOADERS: Record<string, () => Lesson> = {
${body}
};

const loaded: Record<string, Lesson | undefined> = {};

/** The lesson with this id, loading only its own module. */
export function lessonById(id: string | undefined): Lesson | undefined {
  if (!id) return undefined;
  if (id in loaded) return loaded[id];
  const load = LOADERS[id];
  const lesson = load ? load() : undefined;
  loaded[id] = lesson;
  return lesson;
}

export const LOADER_IDS: readonly string[] = Object.keys(LOADERS);
`;
writeFileSync(path.join(DATA, 'lessonLoader.ts'), out);
console.log(`lessonLoader.ts: ${entries.length} lessons`);
