/**
 * Regenerates src/screens/lab/dj/engine/djTrackData.ts from the DJ Systems
 * Lab's music engine (run after any change to djMusic.ts):
 *
 *   node scripts/djTrackData.mjs
 *
 * test/djMusic.test.ts fails when the file is stale.
 */
import { writeFileSync } from 'node:fs';
import { TRACK_IDS, analyseTrack, quantiseOverview, rawPeakOf } from '../src/screens/lab/dj/engine/djMusic.ts';

const rows = [];
for (const id of TRACK_IDS) {
  const o = await analyseTrack(id);
  const q = quantiseOverview(o);
  rows.push(`  ${id}: { rawPeak: ${rawPeakOf(id)}, cols: ${q.cols}, hi: '${q.hi}', lo: '${q.lo}', peak: '${q.peak}' },`);
}
const out = `/**
 * djTrackData — GENERATED by scripts/djTrackData.mjs. Do not edit by hand.
 * The practice tracks' analysis (raw master peak + quantised overview),
 * computed by djMusic.analyseTrack ahead of time so a phone never pays for it.
 * test/djMusic.test.ts recomputes it and fails if this file is stale.
 */
export const TRACK_DATA: Partial<Record<'nightFerry' | 'glassHarbour' | 'slowOrbit', { rawPeak: number; cols: number; hi: string; lo: string; peak: string }>> = {
${rows.join('\n')}
};
`;
writeFileSync(new URL('../src/screens/lab/dj/engine/djTrackData.ts', import.meta.url), out);
console.log('wrote djTrackData.ts');
