/** Storage path ('<bucket>/<file>') for a topic's gs, or null if none. Pass
 *  straight to <TrophyImage iconUrl={topicImagePath(gs)} />. */
export function topicImagePath(gs: number | null | undefined): string | null {
  if (gs == null) return null;
  const f = FILE_BY_GS[gs];
  return f ? `${TOPIC_IMAGE_BUCKET}/${f}` : null;
}

