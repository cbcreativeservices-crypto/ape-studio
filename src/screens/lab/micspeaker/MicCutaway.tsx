/**
 * MicCutaway — the animated dynamic-microphone capsule cutaway (Computer B's
 * asset, APE deep-review + fixes 2026-08-22; review docs in docs/art/mic-cutaway).
 *
 * WHY react-native-svg, not Skia: this is a pure react-native-svg + Reanimated
 * asset, and react-native-svg is already in every build — so unlike the rest of
 * this lab (which gates on Skia) the cutaway renders on EVERY client, including
 * pre-Skia ones. No new native build was needed to add it.
 *
 * HOW it animates without per-frame SVG work: the artwork is emitted as
 * parse-once SvgXml layers (micCutawayAsset.ts, generated by the patch script),
 * each boxed to its own content. A single Reanimated phase clock drives
 * VIEW-level translate / rotate / scaleX / opacity on those layers — the SVGs
 * are parsed once and never re-rendered. This is deliberately the shape the
 * review asked for after the dev-client CPU-runaway watchdog scare: one
 * UI-thread clock, cheap animated props, and the clock cancelled on blur (see
 * the running gate below). Only translate, rotate, scaleX and opacity are used:
 * the transforms an Android View and an iOS layer both apply natively (Android
 * Views cannot skew), so both platforms move the same.
 *
 * The teaching chain (e = B·l·v), all from ONE phase φ (owner 2026-11-22,
 * "needs animation showing coil moving around magnet"):
 *   sound pressure at the diaphragm p ∝ sin φ — the wavefronts march one
 *   wavelength per cycle, so a compression meets the front screen as the
 *   dome-face wash brightens →
 *   the dome, coil seat and voice coil slide along the axis, dx = X·cos φ
 *   (its velocity ∝ −sin φ: inward while p > 0, fastest mid-travel) →
 *   current ∝ velocity: the amber and the glow peak as the coil passes the
 *   middle and fade to nothing at each end of the travel, where the coil stops
 *   and turns back — and the ⊗/⊙ markers flip exactly there (AC).
 * The roll halves rotate about their clamped outer edge and the lead wires flex
 * (scaleX about their dressing point), so nothing tears at either end. All of
 * it is badged ILLUSTRATIVE — travel exaggerated ~1,000×, and the on-art
 * caveat spells out the mass-controlled-cardioid honesty note.
 *
 * Reduced motion: this is a LESSON display (owner ruling 2026-10-02, listed in
 * test/patternP10b_20261002.test.ts) — the moving coil IS the lesson, so it does
 * not read the decorative gate; the host stops it with running={focused}. At
 * rest it holds φ = ¼: the coil mid-travel at full speed, current and glow at
 * their peak, a compression at the screen — a still that tells the whole story.
 */
import { useEffect } from 'react';
import { StyleSheet, View, type ViewStyle } from 'react-native';
import { SvgXml } from 'react-native-svg';
import Animated, {
  cancelAnimation,
  Easing,
  useAnimatedStyle,
  useSharedValue,
  withRepeat,
  withTiming,
} from 'react-native-reanimated';
import { MIC_ASPECT, MIC_LAYERS, MIC_MOTION, MIC_VIEWBOX_BOX, type MicLayer } from './micCutawayAsset';

// One full electrical cycle. The sound field rides the same clock (one
// wavelength per period): before 2026-11-22 it marched on its own 1,100 ms
// loop, which cannot read as the cause of a 1,400 ms coil swing.
const PERIOD_MS = 1400;
const TAU = 2 * Math.PI;
const { travel: X, rollArm: ARM, leadASpan: SPAN_A, leadBSpan: SPAN_B, waveStep: WAVE_STEP } = MIC_MOTION;
const [VB_X, VB_Y, VB_W, VB_H] = MIC_VIEWBOX_BOX;
type Box = MicLayer['box'];

export function MicCutaway({ width, running = true }: { width: number; running?: boolean }) {
  const height = Math.round(width / MIC_ASPECT);
  // The base layers are `meet`-fitted to the card; every other layer is placed
  // with the same scale and offset, so they register on it exactly.
  const k = Math.min(width / VB_W, height / VB_H); // points per viewBox unit
  const ox = (width - VB_W * k) / 2;
  const oy = (height - VB_H * k) / 2;
  /** A layer box in points — on the card, or inside a parent window's box. */
  const place = (b: Box, parent?: Box): ViewStyle => ({
    position: 'absolute',
    left: parent ? (b[0] - parent[0]) * k : ox + (b[0] - VB_X) * k,
    top: parent ? (b[1] - parent[1]) * k : oy + (b[1] - VB_Y) * k,
    width: b[2] * k,
    height: b[3] * k,
  });

  // phase 0→1 = one cycle. sin(2π·phase) is the coil velocity / EMF / current;
  // the displacement is its integral, X·cos(2π·phase).
  const phase = useSharedValue(0.25); // rest at velocity peak (a meaningful still)

  useEffect(() => {
    if (!running) {
      cancelAnimation(phase);
      phase.value = 0.25;
      return;
    }
    phase.value = withRepeat(withTiming(1.25, { duration: PERIOD_MS, easing: Easing.linear }), -1, false);
    return () => {
      cancelAnimation(phase);
    };
  }, [running, phase]);

  // ── the moving assembly (dome + coil seat + voice coil) and what rides on it
  const moveStyle = useAnimatedStyle(() => {
    'worklet';
    return { transform: [{ translateX: X * Math.cos(TAU * phase.value) * k }] };
  });
  const moveTopStyle = useAnimatedStyle(() => {
    'worklet';
    return { transform: [{ translateX: X * Math.cos(TAU * phase.value) * k }] };
  });
  const nearMoveStyle = useAnimatedStyle(() => {
    'worklet';
    return { transform: [{ translateX: X * Math.cos(TAU * phase.value) * k }] };
  });
  // ── the roll halves: rotate about the clamped outer edge so the inner edge
  //    follows the dome by exactly dx (upper turns counter-clockwise for +dx)
  const rollUpperStyle = useAnimatedStyle(() => {
    'worklet';
    const dx = X * Math.cos(TAU * phase.value);
    return { transform: [{ rotate: `${-Math.asin(dx / ARM)}rad` }] };
  });
  const rollLowerStyle = useAnimatedStyle(() => {
    'worklet';
    const dx = X * Math.cos(TAU * phase.value);
    return { transform: [{ rotate: `${Math.asin(dx / ARM)}rad` }] };
  });
  // ── the lead wires' flexing runs: span → span + dx about the dressing point
  const leadAStyle = useAnimatedStyle(() => {
    'worklet';
    return { transform: [{ scaleX: (SPAN_A + X * Math.cos(TAU * phase.value)) / SPAN_A }] };
  });
  const leadBStyle = useAnimatedStyle(() => {
    'worklet';
    return { transform: [{ scaleX: (SPAN_B + X * Math.cos(TAU * phase.value)) / SPAN_B }] };
  });
  // ── induced current ∝ velocity: |sin| on unsigned wiring, the two signed
  //    halves crossfade on the coil so ⊗/⊙ flip at each end of the travel
  const currentLeadAStyle = useAnimatedStyle(() => {
    'worklet';
    const p = TAU * phase.value;
    return { opacity: Math.abs(Math.sin(p)), transform: [{ scaleX: (SPAN_A + X * Math.cos(p)) / SPAN_A }] };
  });
  const currentLeadBStyle = useAnimatedStyle(() => {
    'worklet';
    const p = TAU * phase.value;
    return { opacity: Math.abs(Math.sin(p)), transform: [{ scaleX: (SPAN_B + X * Math.cos(p)) / SPAN_B }] };
  });
  const currentStaticStyle = useAnimatedStyle(() => {
    'worklet';
    return { opacity: Math.abs(Math.sin(TAU * phase.value)) };
  });
  const posStyle = useAnimatedStyle(() => {
    'worklet';
    const s = Math.sin(2 * Math.PI * phase.value);
    return { opacity: Math.max(0, s) };
  });
  const negStyle = useAnimatedStyle(() => {
    'worklet';
    const s = Math.sin(2 * Math.PI * phase.value);
    return { opacity: Math.max(0, -s) };
  });
  // "generating" halo at the coil: brightest mid-travel, gone where it stops
  const glowStyle = useAnimatedStyle(() => {
    'worklet';
    const s = Math.sin(2 * Math.PI * phase.value);
    return { opacity: Math.abs(s) };
  });
  // ── the sound: pressure at the dome face, and the inbound wavefronts
  const nearCompStyle = useAnimatedStyle(() => {
    'worklet';
    return { opacity: Math.max(0, Math.sin(TAU * phase.value)) };
  });
  const nearRareStyle = useAnimatedStyle(() => {
    'worklet';
    return { opacity: Math.max(0, -Math.sin(TAU * phase.value)) };
  });
  const waveStyle = useAnimatedStyle(() => {
    'worklet';
    // MOTION §2: fronts at 168 + (n + ¼ − φ/2π)·34, drawn at φ = 0 → shift by
    // −frac(phase)·34; a compression meets the screen (x 168) at phase ¼.
    const f = phase.value - Math.floor(phase.value);
    return { transform: [{ translateX: -f * WAVE_STEP * k }] };
  });

  const svg = (l: MicLayer) => (
    <SvgXml
      accessibilityElementsHidden
      importantForAccessibility="no-hide-descendants"
      xml={l.xml}
      width={l.box[2] * k}
      height={l.box[3] * k}
    />
  );
  const L = MIC_LAYERS;
  // Static clip windows (a moving layer slides inside a fixed window): the
  // wavefronts end at the front screen's outer face, the dome-face wash at its
  // inner face.
  const waveClip: Box = [MIC_MOTION.waveClipX, L.wave.box[1], VB_X + VB_W - MIC_MOTION.waveClipX, L.wave.box[3]];
  const nearClip: Box = [140, L.nearComp.box[1], MIC_MOTION.nearClipX - 140, L.nearComp.box[3]];

  return (
    <View style={[styles.box, { width, height }]} pointerEvents="none">
      {/* motor, housing, rim flanges, fixed leads' outline */}
      <View style={place(L.under.box)}>{svg(L.under)}</View>
      {/* compliant roll halves */}
      <Animated.View style={[place(L.rollUpper.box), rollUpperStyle]}>{svg(L.rollUpper)}</Animated.View>
      <Animated.View style={[place(L.rollLower.box), rollLowerStyle]}>{svg(L.rollLower)}</Animated.View>
      {/* the moving assembly: dome + coil seat + voice coil */}
      <Animated.View style={[place(L.moving.box), moveStyle]}>{svg(L.moving)}</Animated.View>
      {/* lead wires flex with the coil */}
      <Animated.View style={[place(L.leadA.box), leadAStyle]}>{svg(L.leadA)}</Animated.View>
      <Animated.View style={[place(L.leadB.box), leadBStyle]}>{svg(L.leadB)}</Animated.View>
      {/* fixed lead copper, humbucking coil, lugs, magnetic field */}
      <View style={place(L.overA.box)}>{svg(L.overA)}</View>
      {/* induced current: fixed wiring, each lead, then ON the coil (+ glow) */}
      <Animated.View style={[place(L.currentStatic.box), currentStaticStyle]}>{svg(L.currentStatic)}</Animated.View>
      <Animated.View style={[place(L.currentLeadB.box), currentLeadBStyle]}>{svg(L.currentLeadB)}</Animated.View>
      <Animated.View style={[place(L.currentLeadA.box), currentLeadAStyle]}>{svg(L.currentLeadA)}</Animated.View>
      <Animated.View style={[place(L.currentPos.box), moveTopStyle]}>
        <Animated.View style={[StyleSheet.absoluteFill, posStyle]}>{svg(L.currentPos)}</Animated.View>
        <Animated.View style={[StyleSheet.absoluteFill, negStyle]}>{svg(L.currentNeg)}</Animated.View>
        <Animated.View style={[StyleSheet.absoluteFill, glowStyle]}>{svg(L.glow)}</Animated.View>
      </Animated.View>
      {/* inbound sound field, marching in step with the coil */}
      <View style={[place(waveClip), styles.clip]}>
        <Animated.View style={[place(L.wave.box, waveClip), waveStyle]}>{svg(L.wave)}</Animated.View>
      </View>
      {/* pressure at the dome face (compression / rarefaction), riding with the dome */}
      <View style={[place(nearClip), styles.clip]}>
        <Animated.View style={[place(L.nearComp.box, nearClip), nearMoveStyle]}>
          <Animated.View style={[StyleSheet.absoluteFill, nearCompStyle]}>{svg(L.nearComp)}</Animated.View>
          <Animated.View style={[StyleSheet.absoluteFill, nearRareStyle]}>{svg(L.nearRare)}</Animated.View>
        </Animated.View>
      </View>
      {/* rear path, labels, honesty caveat */}
      <View style={place(L.overB.box)}>{svg(L.overB)}</View>
    </View>
  );
}

const styles = StyleSheet.create({
  box: { position: 'relative', alignSelf: 'center' },
  clip: { overflow: 'hidden' },
});
