const polyPath = (q: Poly): SkPath => {
  const p = Skia.Path.Make();
  p.moveTo(q[0].u, q[0].v);
  for (let i = 1; i < q.length; i++) p.lineTo(q[i].u, q[i].v);
  p.close();
  return p;
};

/** The pole's straight band from `a0` to `a1` mm along its axis, half-width `h`: no ends. */
function band(a0: number, a1: number, h: number, shift: Pt = P(0, 0)): SkPath {
  const c0 = poleTopUnderLowAxisAt(a0);
  const c1 = poleTopUnderLowAxisAt(a1);
  const n = ACROSS;
  const s = shift;
  return polyPath([P(c0.u + n.u * h + s.u, c0.v + n.v * h + s.v), P(c1.u + n.u * h + s.u, c1.v + n.v * h + s.v), P(c1.u - n.u * h + s.u, c1.v - n.v * h + s.v), P(c0.u - n.u * h + s.u, c0.v - n.v * h + s.v)]);
}
function bandSides(a0: number, a1: number): SkPath {
  const c0 = poleTopUnderLowAxisAt(a0);
  const c1 = poleTopUnderLowAxisAt(a1);
  const n = ACROSS;
  const p = Skia.Path.Make();
  for (const s of [1, -1]) {
    p.moveTo(c0.u + n.u * POLE_R_TOP_UNDER_LOW * s, c0.v + n.v * POLE_R_TOP_UNDER_LOW * s);
    p.lineTo(c1.u + n.u * POLE_R_TOP_UNDER_LOW * s, c1.v + n.v * POLE_R_TOP_UNDER_LOW * s);
  }
  return p;
}

const IDENTITY: LightMap = { a: 1, b: 0, c: 0, d: 1 };
const isId = (M: LightMap) => M.a === 1 && M.b === 0 && M.c === 0 && M.d === 1;
const mv = (M: LightMap, u: number, v: number): Pt => P(M.a * u + M.b * v, M.c * u + M.d * v);
/**
 * Soft lights (sign +1) or shades (−1) for the light the map brings (identity: exactly as authored): each moved a little
 * round its form toward the new light, and one on a SIDE of a form (`n`) re-weighed by how that side now faces the light
 * — a light on a side turned away fades, a shade on a side turned toward it fades.
 */
function softs(list: SoftLow[], M: LightMap, sign: 1 | -1, k = 0.35): { p: SkPath; o: number }[] {
  const L = mv(M, LIGHT.u, LIGHT.v);
  const id = isId(M);
  return list.map(({ e, o, n }) => {
    let c = e.c;
    let w = o;
    if (!id) {
      const r = Math.min(e.rx, e.ry) * k * sign;
      c = P(e.c.u + r * (L.u - LIGHT.u), e.c.v + r * (L.v - LIGHT.v));
      if (n) {
        const l = Math.hypot(n.u, n.v) || 1;
        const f0 = (n.u * LIGHT.u + n.v * LIGHT.v) / l;
        const f1 = (n.u * L.u + n.v * L.v) / l;
        const g = (f: number) => Math.max(0, 0.45 + sign * f);
        w = o * Math.min(1.4, g(f1) / Math.max(0.15, g(f0)));
      }
    }
    return { p: ellipsePath({ ...e, c }), o: w };
  });
}
/** The lit edge of a mass for the light the map brings. */
function rimL(path: SkPath, w: number, M: LightMap): SkPath {
  if (isId(M)) return rimOf(path, w);
  const L = mv(M, LIGHT.u, LIGHT.v);
  const q = path.copy();
  q.offset(-L.u * w, -L.v * w);
  return op(path, q, PathOp.Difference);
}
/** A page offset (mm) carried into the drawing's frame: a cast shadow falls the same way on the page. */
const off = (M: LightMap, u: number, v: number) => {
  const q = mv(M, u, v);
  return [{ translateX: q.u }, { translateY: q.v }];
};

/** Each finger's own soft lights and shades, from its axis: the middle joint's bend (the nearest: a soft swell of light),
 *  the first segment's back (toward us, crossing the pole), the groove on its little-finger side, the middle segment and
 *  the last joint turning down and away. */
function fingerForms(f: (typeof TOP_UNDER_LOW_FINGERS)[number], k: number) {
  const mid = (a: Pt, b: Pt, t: number) => P(a.u + (b.u - a.u) * t, a.v + (b.v - a.v) * t);
  const ang = (a: Pt, b: Pt) => Math.atan2(b.v - a.v, b.u - a.u);
  const r = f.r;
  const p1 = ang(f.mcp, f.pip);
  const m1 = ang(f.pip, f.dip);
  const seg = Math.hypot(f.pip.u - f.mcp.u, f.pip.v - f.mcp.v);
  // (each finger its own: the size and place of its lights differ a little)
  const s = [1, 1.1, 0.92, 0.82][k];
  const A1 = ac(1, 0);
  const lights: SoftLow[] = [
    // the middle joint's bend, the nearest part: a broad, low swell of light (a knuckle of the same skin, never a spot)
    { e: { c: P(f.pip.u + A1.u * r * 0.22, f.pip.v + A1.v * r * 0.22), rx: r * 0.86 * s, ry: r * 0.62, rot: m1 }, o: 0.26 },
    // the first segment's back, a long soft light down its index-side half
    { e: { c: P(mid(f.mcp, f.pip, 0.55 + 0.04 * k).u + A1.u * r * 0.22, mid(f.mcp, f.pip, 0.55 + 0.04 * k).v + A1.v * r * 0.22), rx: seg * 0.36 * s, ry: r * 0.4, rot: p1 }, o: 0.2, n: N(0.3, 0.95) },
  ];
  const darks: SoftLow[] = [
    // the groove on its little-finger side (by the next finger)
    { e: { c: P(mid(f.mcp, f.pip, 0.5).u - A1.u * r * 0.74, mid(f.mcp, f.pip, 0.5).v - A1.v * r * 0.74), rx: seg * 0.42, ry: r * 0.3, rot: p1 }, o: 0.24, n: N(-1, 0) },
    // the middle segment and the last joint turning down and away, out of the light
    { e: { c: mid(f.pip, f.dip, 0.66), rx: r * 0.95, ry: r * 0.66, rot: m1 }, o: 0.3, n: N(0, -1) },
  ];
  return { lights, darks };
}

/** The knuckle side: from the knuckle row's foot out past the fist's upper-left edge (no lit rim, no line there). */
const KNUCKLE_ZONE: Poly = pts([[-80, 12], [60, 12], [60, 70], [-80, 70]]);

/** A shape grown by `w` mm all round (with its drawn edge inside). */
function grown(p: SkPath, w: number): SkPath {
  const moved = [0, 1, 2, 3, 4, 5, 6, 7].map((k) => {
    const q = p.copy();
    q.offset(w * Math.cos((k * Math.PI) / 4), w * Math.sin((k * Math.PI) / 4));
    return q;
  });
  return unionOf(p, ...moved);
}

function build(a: PoleHandTopUnderLowArt, a0: number, a1: number, M: LightMap, sleeveOn: boolean) {
  const sleeve = smoothClosed(a.sleeve, 0.2);
  const cut = polyPath(SLEEVE_CUT);
  const body0 = smoothClosed(a.body, 0.5);
  const body = sleeveOn ? body0 : op(body0, cut, PathOp.Difference);
  const fingers = a.fingers.map((q) => smoothClosed(q, 0.5));
  const thumb = smoothClosed(a.thumb, 0.5);
  const group = unionOf(...fingers);
  const all = unionOf(body, group, thumb);
  const big = Skia.Path.Make();
  big.addRect(Skia.XYWHRect(-400, -400, 800, 800));
  const noSleeve = sleeveOn ? null : op(big, cut, PathOp.Difference);
  const pole = band(a0, a1, POLE_R_TOP_UNDER_LOW);
  const forms = a.fingerAxes.map((f, k) => fingerForms(f, k));
  const litOff = mv(M, BOOM_LIT_OFF.u, BOOM_LIT_OFF.v);
  const knuckleZone = smoothClosed(KNUCKLE_ZONE, 0.3);
  // (a finger's soft shadow comes from its part below the knuckle row only: it fades out toward the knuckles)
  const shadowSrc = fingers.map((f) => op(f, knuckleZone, PathOp.Difference));
  const L = mv(M, LIGHT.u, LIGHT.v);
  return {
    M,
    sleeveOn,
    sleeve,
    noSleeve,
    body,
    fingers,
    group,
    thumb,
    all,
    pole,
    poleSides: bandSides(a0, a1),
    /** (poleLook 'boom') where this drawing paints the pole: its silhouette inside the hand's outline (the scene draws
     *  the pole whole under the hand; the hand's body would hide it there — over the wrist too). */
    poleClip: op(grown(all, 1.2), pole, PathOp.Intersect),
    poleBoom: [op(band(a0, a1, 15.5), band(a0, a1, 13.5), PathOp.Difference), band(a0, a1, 13.5), band(a0, a1, 3, litOff)] as const,
    /** the pole's soft shadow falls on the skin beside it (the heel, the wrist, the thumb's root), never on the pole */
    poleShadowOn: op(unionOf(body, thumb), pole, PathOp.Difference),
    /** where each finger's soft shadow may fall: the pole, the thumb, the fingers before it */
    fingerShadowOn: fingers.map((_, i) => unionOf(pole, thumb, ...fingers.slice(0, i))),
    shadowSrc,
    knuckleZone,
    cuffOpening: ellipsePath(a.cuff),
    fingerEdges: a.fingerEdges.map((e) => smoothOpen(e)),
    thumbEdge: smoothOpen(a.thumbEdge),
    thumbNail: smoothClosed(a.thumbNail),
    /** the fingers' drawn edges fade in from the knuckle side (transparent at the row's foot, full a little over the pole):
     *  [from, to]; the index's outer edge is the fist's outline and does not fade */
    fade: [ac(0, 15), ac(0, 6)] as const,
    lights: softs(a.lights, M, 1),
    darks: softs(a.darks, M, -1),
    fingerLights: forms.map((f) => softs(f.lights, M, 1)),
    fingerDarks: forms.map((f) => softs(f.darks, M, -1)),
    /** each finger round across its first segment (lit on the side toward the light) and darker toward its end, past its
     *  middle joint, where it turns down out of the light: [start, end] of the across light, [start, end] of the end's
     *  shade */
    fingerRound: a.fingerAxes.map((f) => {
      const m = Math.atan2(f.pip.v - f.mcp.v, f.pip.u - f.mcp.u);
      const n0 = P(Math.sin(m), -Math.cos(m));
      const n = n0.u * L.u + n0.v * L.v >= 0 ? n0 : P(-n0.u, -n0.v);
      const c = P(f.mcp.u + (f.pip.u - f.mcp.u) * 0.6, f.mcp.v + (f.pip.v - f.mcp.v) * 0.6);
      return {
        across: [P(c.u + n.u * f.r * 1.05, c.v + n.v * f.r * 1.05), P(c.u - n.u * f.r * 1.05, c.v - n.v * f.r * 1.05)] as const,
        along: [P(f.pip.u + (f.dip.u - f.pip.u) * 0.05, f.pip.v + (f.dip.v - f.pip.v) * 0.05), P(f.dip.u + (f.dip.u - f.pip.u) * 0.3, f.dip.v + (f.dip.v - f.pip.v) * 0.3)] as const,
      };
    }),
    /** the thumb round across its end segment: in the fingers' ends' shade on its inner side, turning away on its outer */
    thumbAcross: [ac(14, -27), ac(14, -49)] as const,
    thumbLights: softs(a.thumbLights, M, 1),
    thumbDarks: softs(a.thumbDarks, M, -1),
    bodyRim: rimL(body, 2, M),
  };
}
