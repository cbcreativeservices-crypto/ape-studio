const many = (ps: SkPath[]): SkPath => {
  const p = Skia.Path.Make();
  for (const q of ps) p.addPath(q);
  return p;
};
const polyPath = (q: Poly): SkPath => {
  const p = Skia.Path.Make();
  p.moveTo(q[0].u, q[0].v);
  for (let i = 1; i < q.length; i++) p.lineTo(q[i].u, q[i].v);
  p.close();
  return p;
};

/** The pole's straight band from `a0` to `a1` mm along its axis, half-width `h`: no ends. */
function band(a0: number, a1: number, h: number, shift: Pt = P(0, 0)): SkPath {
  const c0 = poleTopUnderAxisAt(a0);
  const c1 = poleTopUnderAxisAt(a1);
  const n = ACROSS;
  const s = shift;
  return polyPath([P(c0.u + n.u * h + s.u, c0.v + n.v * h + s.v), P(c1.u + n.u * h + s.u, c1.v + n.v * h + s.v), P(c1.u - n.u * h + s.u, c1.v - n.v * h + s.v), P(c0.u - n.u * h + s.u, c0.v - n.v * h + s.v)]);
}
function bandSides(a0: number, a1: number): SkPath {
  const c0 = poleTopUnderAxisAt(a0);
  const c1 = poleTopUnderAxisAt(a1);
  const n = ACROSS;
  const p = Skia.Path.Make();
  for (const s of [1, -1]) {
    p.moveTo(c0.u + n.u * POLE_R_TOP_UNDER * s, c0.v + n.v * POLE_R_TOP_UNDER * s);
    p.lineTo(c1.u + n.u * POLE_R_TOP_UNDER * s, c1.v + n.v * POLE_R_TOP_UNDER * s);
  }
  return p;
}

const IDENTITY: LightMap = { a: 1, b: 0, c: 0, d: 1 };
const isId = (M: LightMap) => M.a === 1 && M.b === 0 && M.c === 0 && M.d === 1;
const mv = (M: LightMap, u: number, v: number): Pt => P(M.a * u + M.b * v, M.c * u + M.d * v);
/**
 * Soft lights (sign +1) or shades (−1) for the light the map brings (identity: exactly as authored): each moved a little
 * round its form toward the new light, and one on a SIDE of a form (`n`) re-weighed by how that side now faces the light
 * — a light on a side turned away fades, a shade on a side turned toward it fades.
 */
function softs(list: Soft[], M: LightMap, sign: 1 | -1, k = 0.35): { p: SkPath; o: number }[] {
  const L = mv(M, LIGHT.u, LIGHT.v);
  const id = isId(M);
  return list.map(({ e, o, n }) => {
    let c = e.c;
    let w = o;
    if (!id) {
      const r = Math.min(e.rx, e.ry) * k * sign;
      c = P(e.c.u + r * (L.u - LIGHT.u), e.c.v + r * (L.v - LIGHT.v));
      if (n) {
        const l = Math.hypot(n.u, n.v) || 1;
        const f0 = (n.u * LIGHT.u + n.v * LIGHT.v) / l;
        const f1 = (n.u * L.u + n.v * L.v) / l;
        const g = (f: number) => Math.max(0, 0.45 + sign * f);
        w = o * Math.min(1.4, g(f1) / Math.max(0.15, g(f0)));
      }
    }
    return { p: ellipsePath({ ...e, c }), o: w };
  });
}
/** The lit edge of a mass for the light the map brings. */
function rimL(path: SkPath, w: number, M: LightMap): SkPath {
  if (isId(M)) return rimOf(path, w);
  const L = mv(M, LIGHT.u, LIGHT.v);
  const q = path.copy();
  q.offset(-L.u * w, -L.v * w);
  return op(path, q, PathOp.Difference);
}
/** A page offset (mm) carried into the drawing's frame: a cast shadow falls the same way on the page. */
const off = (M: LightMap, u: number, v: number) => {
  const q = mv(M, u, v);
  return [{ translateX: q.u }, { translateY: q.v }];
};

/** Each finger's own soft lights and shades, from its axis: the first segment's back (facing the light), the middle
 *  joint's bend (the nearest: lit), the middle segment's top over the pole, the side away from the light, the last
 *  joint turning down. */
function fingerForms(f: (typeof TOP_UNDER_FINGERS)[number], k: number) {
  const mid = (a: Pt, b: Pt, t: number) => P(a.u + (b.u - a.u) * t, a.v + (b.v - a.v) * t);
  const ang = (a: Pt, b: Pt) => Math.atan2(b.v - a.v, b.u - a.u);
  const r = f.r;
  const m1 = ang(f.pip, f.dip);
  const p1 = ang(f.mcp, f.pip);
  const up = (a: number) => P(Math.sin(a), -Math.cos(a));
  // (each finger its own: the size and place of its lights differ a little)
  const s = [1, 0.86, 1.08, 0.8][k];
  const u = up(m1);
  const lights: Soft[] = [
    // the middle joint's bend, the nearest part: a soft swell of light (a knuckle of the same skin, never a spot)
    { e: { c: P(f.pip.u + u.u * r * 0.2 - 0.8, f.pip.v + u.v * r * 0.2 - 0.5), rx: r * 0.78 * s, ry: r * 0.56, rot: m1 - 0.45 }, o: 0.3 },
    // the middle segment's back over the pole, a long soft light along its upper half
    { e: { c: mid(P(f.pip.u + u.u * r * 0.28, f.pip.v + u.v * r * 0.28), P(f.dip.u + u.u * r * 0.28, f.dip.v + u.v * r * 0.28), 0.4), rx: r * 1.15, ry: r * 0.34, rot: m1 }, o: 0.24, n: u },
    // the first segment's back (toward the knuckle side): faces the light
    { e: { c: mid(f.mcp, f.pip, 0.42 + 0.06 * k), rx: r * 0.95, ry: r * 0.36, rot: p1 }, o: 0.24, n: P(-1, -0.35) },
  ];
  const darks: Soft[] = [
    // the lower side along the middle segment (turning away, toward the finger below)
    { e: { c: mid(P(f.pip.u - u.u * r * 0.66, f.pip.v - u.v * r * 0.66), P(f.dip.u - u.u * r * 0.66, f.dip.v - u.v * r * 0.66), 0.46), rx: r * 1.4, ry: r * 0.34, rot: m1 }, o: 0.3, n: P(-u.u, -u.v) },
    // the last joint turning down past the pole's edge, out of the light
    { e: { c: P(f.dip.u + 3.4, f.dip.v + 0.8), rx: r * 0.46, ry: r * 0.86, rot: m1 }, o: 0.3, n: P(1, 0.25) },
  ];
  return { lights, darks };
}

