const KNUCKLE_ZONE: Poly = pts([[-90, -90], [2, -90], [-2, -56], [-11, -24], [-16.4, -6], [-20.6, 11], [-23.4, 27], [-30, 52], [-90, 60]]);

/** A shape grown by `w` mm all round (with its drawn edge inside). */
function grown(p: SkPath, w: number): SkPath {
  const moved = [0, 1, 2, 3, 4, 5, 6, 7].map((k) => {
    const q = p.copy();
    q.offset(w * Math.cos((k * Math.PI) / 4), w * Math.sin((k * Math.PI) / 4));
    return q;
  });
  return unionOf(p, ...moved);
}

function build(a: PoleHandTopUnderArt, a0: number, a1: number, M: LightMap, sleeveOn: boolean) {
  const sleeve = smoothClosed(a.sleeve, 0.2);
  const cut = polyPath(SLEEVE_CUT);
  const body0 = smoothClosed(a.body, 0.5);
  const body = sleeveOn ? body0 : op(body0, cut, PathOp.Difference);
  const fingers = a.fingers.map((q) => smoothClosed(q, 0.5));
  const thumb = smoothClosed(a.thumb, 0.5);
  const group = unionOf(...fingers);
  const all = unionOf(body, group, thumb);
  const big = Skia.Path.Make();
  big.addRect(Skia.XYWHRect(-400, -400, 800, 800));
  const noSleeve = sleeveOn ? null : op(big, cut, PathOp.Difference);
  const pole = band(a0, a1, POLE_R_TOP_UNDER);
  const forms = a.fingerAxes.map((f, k) => fingerForms(f, k));
  const litOff = mv(M, BOOM_LIT_OFF.u, BOOM_LIT_OFF.v);
  return {
    M,
    sleeveOn,
    sleeve,
    noSleeve,
    body,
    fingers,
    group,
    thumb,
    all,
    pole,
    poleSides: bandSides(a0, a1),
    /** (poleLook 'boom') where this drawing paints the pole: its silhouette inside the hand's outline (the scene draws
     *  the pole whole under the hand; the hand's body would hide it there). */
    poleClip: op(grown(all, 1.2), pole, PathOp.Intersect),
    poleBoom: [op(band(a0, a1, 15.5), band(a0, a1, 13.5), PathOp.Difference), band(a0, a1, 13.5), band(a0, a1, 3, litOff)] as const,
    /** where the pole passes in FRONT of the thumb's base (the thumb comes up the pole's near side from under it): the
     *  pole painted again there, over the thumb */
    overThumb: op(op(pole, grown(thumb, 1.2), PathOp.Intersect), polyPath(UPPER), PathOp.Intersect),
    thumbShadowOn: op(unionOf(group, pole), op(pole, polyPath(UPPER), PathOp.Intersect), PathOp.Difference),
    /** the knuckle side, where the fingers grow out of the hand: beyond their middle joints toward their knuckles */
    knuckleZone: smoothClosed(KNUCKLE_ZONE, 0.3),
    cuffOpening: ellipsePath(a.cuff),
    fingerEdges: a.fingerEdges.map((e) => smoothOpen(e)),
    thumbEdge: smoothOpen(a.thumbEdge),
    thumbTail: smoothOpen(a.thumbTail),
    /** the tail's fade: full at its start, gone where it goes into the mound */
    thumbTailFade: [a.thumbTail[1], a.thumbTail[a.thumbTail.length - 1]] as const,
    thumbNail: smoothClosed(a.thumbNail),
    creases: many(a.creases.map(smoothOpen)),
    /** each finger's drawn edge fades in from the knuckle side (a quarter → half way from its knuckle to its last joint) */
    fades: a.fingerAxes.map((f, k) => (k === 3 ? null : ([P(f.mcp.u + (f.dip.u - f.mcp.u) * 0.22, f.mcp.v + (f.dip.v - f.mcp.v) * 0.22), P(f.mcp.u + (f.dip.u - f.mcp.u) * 0.48, f.mcp.v + (f.dip.v - f.mcp.v) * 0.48)] as const))),
    lights: softs(a.lights, M, 1),
    darks: softs(a.darks, M, -1),
    fingerLights: forms.map((f) => softs(f.lights, M, 1)),
    fingerDarks: forms.map((f) => softs(f.darks, M, -1)),
    /** each finger round across its length (lit on the side toward the light) and darker toward its end, where it turns
     *  down past the pole's edge: [start, end] of the across light, [start, end] of the end's shade */
    fingerRound: a.fingerAxes.map((f) => {
      const m = Math.atan2(f.dip.v - f.pip.v, f.dip.u - f.pip.u);
      const L = mv(M, LIGHT.u, LIGHT.v);
      const n0 = P(Math.sin(m), -Math.cos(m));
      const n = n0.u * L.u + n0.v * L.v >= 0 ? n0 : P(-n0.u, -n0.v);
      const c = P((f.pip.u + f.dip.u) / 2, (f.pip.v + f.dip.v) / 2);
      return {
        across: [P(c.u + n.u * f.r * 1.05, c.v + n.v * f.r * 1.05), P(c.u - n.u * f.r * 1.05, c.v - n.v * f.r * 1.05)] as const,
        along: [P(f.pip.u + (f.dip.u - f.pip.u) * 0.55, f.pip.v + (f.dip.v - f.pip.v) * 0.55), P(f.tip.u + (f.tip.u - f.dip.u) * 0.4, f.tip.v + (f.tip.v - f.dip.v) * 0.4)] as const,
      };
    }),
    thumbLights: softs(a.thumbLights, M, 1),
    thumbDarks: softs(a.thumbDarks, M, -1),
    bodyRim: rimL(body, 2, M),
  };
}
