/** An ellipse as points (hand frame, turned). */
function arc(cx: number, cy: number, rx: number, ry: number, from: number, to: number, n = 16): Poly {
  const out: Poly = [];
  for (let j = 0; j <= n; j++) {
    const t = from + ((to - from) * j) / n;
    out.push(turn(cx + rx * Math.cos(t), cy + ry * Math.sin(t)));
  }
  return out;
}

